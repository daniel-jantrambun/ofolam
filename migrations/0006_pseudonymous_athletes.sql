-- Migration number: 0006
-- Athletes are no longer stored under their provider id: `id` / `athlete_id` now hold
-- HMAC-SHA256(provider:id) under the ATHLETE_ID_KEY secret (see worker/crypto.ts), and the first
-- name is dropped. Existing rows cannot be converted in SQL (no HMAC in SQLite), so the tables are
-- rebuilt empty: every athlete signs in again (one tap) and their saved templates are lost.

DROP TABLE IF EXISTS templates;
DROP TABLE IF EXISTS sessions;
DROP TABLE IF EXISTS athletes;
DELETE FROM oauth_states;

CREATE TABLE athletes (
  provider TEXT NOT NULL,
  id TEXT NOT NULL,                 -- HMAC of the provider's athlete id (base64url)
  country TEXT,
  access_token TEXT NOT NULL,       -- AES-GCM encrypted
  refresh_token TEXT NOT NULL,      -- AES-GCM encrypted
  expires_at INTEGER NOT NULL,      -- epoch seconds
  scope TEXT,
  updated_at INTEGER NOT NULL,
  PRIMARY KEY (provider, id)
);

CREATE TABLE sessions (
  id_hash TEXT PRIMARY KEY,         -- SHA-256 of the session token
  provider TEXT NOT NULL,
  athlete_id TEXT NOT NULL,         -- athletes.id
  created_at INTEGER NOT NULL,
  last_seen_at INTEGER NOT NULL
);

CREATE TABLE templates (
  provider TEXT NOT NULL,
  athlete_id TEXT NOT NULL,         -- athletes.id
  id TEXT NOT NULL,                 -- random id generated by the worker
  name TEXT NOT NULL,
  options TEXT NOT NULL,            -- JSON (TemplateOptions, see src/lib/templates.ts)
  created_at INTEGER NOT NULL,
  PRIMARY KEY (provider, athlete_id, id)
);
